// State Management
let currentLang = 'fr';

document.addEventListener('DOMContentLoaded', () => {
    initNavigation();
    initLanguageSwitcher();
    initForms();
    initCategoryButtons();
});

// Navigation Toggle
function initNavigation() {
    const hamburger = document.getElementById('hamburger');
    const navMenu = document.getElementById('nav-menu');
    
    if (hamburger && navMenu) {
        hamburger.addEventListener('click', () => {
            navMenu.classList.toggle('active');
        });

        document.querySelectorAll('.nav-link').forEach(link => {
            link.addEventListener('click', () => {
                navMenu.classList.remove('active');
            });
        });
    }
}

// Language Switcher Logic
function initLanguageSwitcher() {
    const btnFr = document.getElementById('lang-btn-fr');
    const btnEn = document.getElementById('lang-btn-en');

    btnFr.addEventListener('click', () => switchLanguage('fr'));
    btnEn.addEventListener('click', () => switchLanguage('en'));
}

function switchLanguage(lang) {
    currentLang = lang;
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
    document.getElementById(`lang-btn-${lang}`).classList.add('active');

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (translations[lang][key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
}

// Pre-fill Category in Quote Form
function initCategoryButtons() {
    document.querySelectorAll('.quote-cat').forEach(btn => {
        btn.addEventListener('click', (e) => {
            const cat = e.target.getAttribute('data-cat');
            const catSelect = document.getElementById('quote-category');
            if (catSelect && cat) {
                catSelect.value = cat;
            }
        });
    });
}

// Form Validation & Submission Simulation (Vercel API Ready)
function initForms() {
    handleFormSubmit('quote-form', 'quote-message', 'Votre demande de devis a été envoyée avec succès ! Notre équipe vous répondra sous 24h.');
    handleFormSubmit('partner-form', 'partner-message', 'Votre proposition de partenariat a été bien reçue. Merci pour votre intérêt pour BYGL.');
    handleFormSubmit('project-form', 'project-message', 'Votre projet a été soumis pour étude de pré-recevabilité par l’équipe de BYGL.');
}

function handleFormSubmit(formId, messageId, successText) {
    const form = document.getElementById(formId);
    const messageContainer = document.getElementById(messageId);

    if (form) {
        form.addEventListener('submit', async (e) => {
            e.preventDefault();
            
            // Show loading status
            const submitBtn = form.querySelector('button[type="submit"]');
            const originalText = submitBtn.textContent;
            submitBtn.disabled = true;
            submitBtn.textContent = currentLang === 'fr' ? 'Traitement en cours...' : 'Processing...';

            // Simulate API request delay
            setTimeout(() => {
                messageContainer.className = 'form-message success';
                messageContainer.textContent = successText;
                form.reset();
                submitBtn.disabled = false;
                submitBtn.textContent = originalText;
            }, 1200);
        });
    }
}
